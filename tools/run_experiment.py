#!/usr/bin/env python3
"""Sanity-gate, multi-seed runner, and repro.sh emitter for an ExperimentPlan.

Reads a plan body from thoughts/<EXP-id>.md (frontmatter JSON), then runs
either:
  --sanity : 60s overfit-32-examples gate
  --run    : full multi-seed proposed + baseline sweep, aggregated to result.json

Each invocation of code/run.py is captured to runs/<timestamp>.log, with a
hard timeout = compute_budget_minutes * 60.

The plan's `code_skeleton` is expected to write JSONL records to stdout of the
form {"seed": int, "config": "proposed"|"baseline", "<metric>": float, ...}.
The runner aggregates these into result.json and prints a one-line summary.

Generates experiments/<EXP-id>/repro.sh for reproducibility.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import statistics
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from _paths import REPO, experiments_dir, project_dir, thoughts_dir


def load_plan(plan_id: str) -> dict:
    """Pull the plan body's frontmatter JSON from <project>/thoughts/<id>.md."""
    body_path = thoughts_dir() / f"{plan_id}.md"
    if not body_path.exists():
        raise SystemExit(f"plan body missing: {body_path}")
    text = body_path.read_text()
    m = re.match(r"---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    if not m:
        raise SystemExit(f"plan body has no frontmatter JSON: {body_path}")
    return json.loads(m.group(1))


def hash_file(p: Path) -> str:
    if not p.exists():
        return ""
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12]


def emit_repro(exp_dir: Path, plan: dict):
    code = exp_dir / "code" / "run.py"
    repro = exp_dir / "repro.sh"
    code_hash = hash_file(code)
    seeds = plan.get("seeds", [])
    body = f"""#!/usr/bin/env bash
# Reproduce experiment {plan['id']}. Generated by tools/run_experiment.py.
set -euo pipefail
cd "$(dirname "$0")"

# code/run.py sha256 prefix at generation time: {code_hash}
# uv.lock sha256 prefix: {hash_file(REPO / 'uv.lock')}
# generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}

mkdir -p runs
"""
    for seed in seeds:
        for cfg in ("baseline", "proposed"):
            body += (
                f'uv run python code/run.py --seed {seed} --config {cfg} '
                f'--out "runs/$(date -u +%Y%m%dT%H%M%SZ)_{cfg}_s{seed}.jsonl"\n'
            )
    body += "echo done\n"
    repro.write_text(body)
    repro.chmod(0o755)


def run_one(
    code: Path,
    seed: int,
    config: str,
    runs_dir: Path,
    timeout_s: int,
    extra_args: list[str] | None = None,
) -> tuple[int, Path, list[dict]]:
    runs_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = runs_dir / f"{ts}_{config}_s{seed}.log"
    out = runs_dir / f"{ts}_{config}_s{seed}.jsonl"
    cmd = [
        "uv",
        "run",
        "python",
        str(code),
        "--seed",
        str(seed),
        "--config",
        config,
        "--out",
        str(out),
        *(extra_args or []),
    ]
    with log.open("w") as lf:
        lf.write(f"# cmd: {' '.join(cmd)}\n")
        lf.flush()
        try:
            r = subprocess.run(
                cmd,
                stdout=lf,
                stderr=subprocess.STDOUT,
                cwd=REPO,
                timeout=timeout_s,
                check=False,
            )
            rc = r.returncode
        except subprocess.TimeoutExpired:
            lf.write("\n# TIMEOUT\n")
            rc = 124
    records = []
    if out.exists():
        for line in out.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return rc, log, records


def aggregate(per_run: list[dict], plan: dict) -> dict:
    """Group records by config, compute mean/stddev for each numeric field."""
    by_config: dict[str, list[dict]] = {}
    for rec in per_run:
        by_config.setdefault(rec.get("config", "?"), []).append(rec)

    metrics_out = {}
    metric_names = plan.get("metrics", [])
    for cfg, rows in by_config.items():
        cfg_metrics = {}
        for m in metric_names:
            vals = [r[m] for r in rows if isinstance(r.get(m), (int, float))]
            if not vals:
                continue
            cfg_metrics[m] = {
                "mean": statistics.fmean(vals),
                "stddev": statistics.pstdev(vals) if len(vals) > 1 else 0.0,
                "n_seeds": len(vals),
                "per_seed": vals,
            }
        metrics_out[cfg] = cfg_metrics
    return metrics_out


def cmd_sanity(plan: dict, exp_dir: Path) -> int:
    code = exp_dir / "code" / "run.py"
    if not code.exists():
        print(json.dumps({"error": "code/run.py missing", "plan_id": plan["id"]}))
        return 2
    runs_dir = exp_dir / "runs"
    rc, log, records = run_one(
        code,
        seed=0,
        config="proposed",
        runs_dir=runs_dir,
        timeout_s=120,
        extra_args=["--sanity"],
    )
    delta = None
    sanity_pass = False
    for r in records:
        if "sanity_loss_initial" in r and "sanity_loss_final" in r:
            initial = r["sanity_loss_initial"]
            final = r["sanity_loss_final"]
            if initial > 0:
                delta = (initial - final) / initial
                sanity_pass = delta >= 0.5 and rc == 0
            break
    print(
        json.dumps(
            {
                "plan_id": plan["id"],
                "sanity_pass": sanity_pass,
                "delta_loss_frac": delta,
                "exit_code": rc,
                "log": str(log.relative_to(REPO)),
            }
        )
    )
    return 0 if sanity_pass else 1


def cmd_run(plan: dict, exp_dir: Path) -> int:
    seeds = plan.get("seeds")
    baseline = plan.get("baseline_spec")
    if not seeds or len(seeds) < 3:
        raise SystemExit(f"plan {plan['id']} missing seeds (need >=3)")
    if not baseline:
        raise SystemExit(f"plan {plan['id']} missing baseline_spec")

    code = exp_dir / "code" / "run.py"
    if not code.exists():
        raise SystemExit(f"plan {plan['id']} missing experiments/{plan['id']}/code/run.py")

    budget_min = int(plan.get("compute_budget_minutes", 30))
    per_run_timeout = max(60, int(budget_min * 60 / max(1, len(seeds) * 2)))

    all_records: list[dict] = []
    runs_dir = exp_dir / "runs"
    for seed in seeds:
        for cfg in ("baseline", "proposed"):
            rc, log, records = run_one(
                code, seed=int(seed), config=cfg, runs_dir=runs_dir, timeout_s=per_run_timeout
            )
            for r in records:
                r.setdefault("seed", seed)
                r.setdefault("config", cfg)
            all_records.extend(records)
            if rc not in (0, 124):
                print(
                    json.dumps(
                        {
                            "plan_id": plan["id"],
                            "status": "crash",
                            "failing_log": str(log.relative_to(REPO)),
                            "seed": seed,
                            "config": cfg,
                            "exit_code": rc,
                        }
                    )
                )
                return 2

    metrics = aggregate(all_records, plan)
    result = {
        "plan_id": plan["id"],
        "metrics": metrics,
        "n_records": len(all_records),
        "completed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    (exp_dir / "result.json").write_text(json.dumps(result, indent=2))

    emit_repro(exp_dir, plan)

    pred_metric = None
    pred_threshold = None
    pred_direction = None
    hyp_id = plan.get("hypothesis_id")
    if hyp_id:
        hyp_path = thoughts_dir() / f"{hyp_id}.md"
        if hyp_path.exists():
            m = re.match(r"---\s*\n(.*?)\n---\s*\n", hyp_path.read_text(), re.DOTALL)
            if m:
                hyp = json.loads(m.group(1))
                pred_metric = hyp.get("prediction_metric")
                pred_threshold = hyp.get("prediction_threshold")
                pred_direction = hyp.get("prediction_direction")

    status = "fail"
    if pred_metric and pred_metric in metrics.get("proposed", {}):
        proposed = metrics["proposed"][pred_metric]["mean"]
        baseline_m = metrics.get("baseline", {}).get(pred_metric, {}).get("mean", 0.0)
        delta = proposed - baseline_m
        if pred_direction == "greater":
            status = "pass" if delta >= float(pred_threshold or 0) else "fail"
        elif pred_direction == "less":
            status = "pass" if -delta >= float(pred_threshold or 0) else "fail"
        elif pred_direction == "equal-within":
            status = "pass" if abs(delta) <= float(pred_threshold or 0) else "fail"

    print(
        json.dumps(
            {
                "plan_id": plan["id"],
                "status": status,
                "n_records": len(all_records),
                "result_path": str((exp_dir / "result.json").relative_to(REPO)),
                "pred_metric": pred_metric,
                "pred_threshold": pred_threshold,
                "pred_direction": pred_direction,
            }
        )
    )
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan-id", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--sanity", action="store_true")
    g.add_argument("--run", action="store_true")
    args = ap.parse_args()

    plan = load_plan(args.plan_id)
    exp_dir = experiments_dir() / args.plan_id
    exp_dir.mkdir(parents=True, exist_ok=True)
    (exp_dir / "code").mkdir(exist_ok=True)
    (exp_dir / "runs").mkdir(exist_ok=True)

    if args.sanity:
        sys.exit(cmd_sanity(plan, exp_dir))
    if args.run:
        sys.exit(cmd_run(plan, exp_dir))


if __name__ == "__main__":
    main()
